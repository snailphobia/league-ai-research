"""Narrow backend protocol; importing it never attempts desktop input."""

from typing import Protocol

from .types import Button, Desktop, Key


class Backend(Protocol):
    def resolve(self, key: str | Key) -> Key: ...
    def identity(self, key: Key) -> Key: ...
    def key_event(self, key: Key, down: bool) -> None: ...
    def button_event(self, button: Button, down: bool) -> None: ...
    def move_to(self, x: int, y: int, duration: float) -> None: ...
    def move_relative(self, dx: int, dy: int) -> None: ...
    def scroll(self, ticks: int, horizontal: bool) -> None: ...
    def position(self) -> tuple[int, int]: ...
    def desktop(self) -> Desktop: ...
    def contains(self, x: int, y: int) -> bool: ...
    def keys(self) -> tuple[str, ...]: ...
